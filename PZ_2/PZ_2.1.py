""" С начала суток прошло N секунд (N — целое). Найти количество
секунд, прошедших с начала последнего часа."""
try:
    N = int(input("Введите количество секунд с начала суток (N): "))
    seconds_since_last_hour = N % 3600
    print("С начала последнего часа прошло:", seconds_since_last_hour, "секунд")
except ValueError:
    print("Ошибка: пожалуйста, введите целое число.")
